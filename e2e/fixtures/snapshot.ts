export function makePrDetail(pr: PrView = makePrView()): PrDetailResponse {
  const checks: PrDetailCheck[] = [
    ...pr.ci.failing.map((check) => ({
      name: check.name,
      kind: 'CheckRun' as const,
      status: 'COMPLETED',
      conclusion: 'FAILURE',
      bucket: 'failing' as const,
      url: check.url,
      description: null,
      startedAt: pr.updatedAt,
      completedAt: pr.updatedAt,
    })),
    ...Array.from({ length: pr.ci.passing }, (_, index) => ({
      name: `check-${index + 1}`,
      kind: 'CheckRun' as const,
      status: 'COMPLETED',
      conclusion: 'SUCCESS',
      bucket: 'passing' as const,
      url: `${pr.url}/checks`,
      description: null,
      startedAt: pr.updatedAt,
      completedAt: pr.updatedAt,
    })),
    ...Array.from({ length: pr.ci.pending }, (_, index) => ({
      name: `pending-${index + 1}`,
      kind: 'CheckRun' as const,
      status: 'IN_PROGRESS',
      conclusion: null,
      bucket: 'pending' as const,
      url: `${pr.url}/checks`,
      description: null,
      startedAt: pr.updatedAt,
      completedAt: null,
    })),
  ];

  const reviewers: PrReviewerDetail[] = [
    ...pr.review.approvals.map((login) => ({
      login,
      kind: 'user' as const,
      state: 'APPROVED' as const,
      submittedAt: pr.updatedAt,
      asCodeOwner: false,
    })),
    ...pr.review.changesRequested.map((login) => ({
      login,
      kind: 'user' as const,
      state: 'CHANGES_REQUESTED' as const,
      submittedAt: pr.updatedAt,
      asCodeOwner: false,
    })),
    ...pr.review.pending.map((login) => ({
      login,
      kind: 'user' as const,
      state: 'PENDING' as const,
      submittedAt: null,
      asCodeOwner: false,
    })),
  ];

  return {
    key: pr.key,
    owner: pr.owner,
    repo: pr.repo,
    number: pr.number,
    title: pr.title,
    url: pr.url,
    baseRefName: pr.baseRefName,
    headRefName: pr.headRefName,
    isDraft: pr.isDraft,
    bodyExcerpt: 'Summary of changes for this pull request.',
    bodyHtml: '<p>Summary of changes for this pull request.</p>',
    checksTotalCount: checks.length + pr.ci.hiddenCount,
    checks,
    reviewers,
    timeline: [
      {
        id: `${pr.key}-commit-1`,
        kind: 'commit',
        actor: pr.author,
        createdAt: pr.lastCommittedAt,
        summary: pr.title,
      },
    ],
    fetchedAt: new Date().toISOString(),
  };
}
